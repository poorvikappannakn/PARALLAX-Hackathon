import { readdirSync, unlinkSync, writeFileSync } from "node:fs";
import path from "node:path";
import { z } from "zod";
import { emailContentLabel, fileContentLabel, webContentLabel } from "../policy/classification.js";
import {
  SandboxError,
  containedDir,
  readContainedFile,
  resolveContainedFile,
  type RunSandbox,
} from "../sandbox/sandbox.js";
import { joinLabels, labeled, makeLabel, type Label, type Labeled } from "../shield/provenance.js";

// Tool implementations. Only the executor (./index.ts) may call these, after redeeming a PEP-issued ticket.
// Every output is labelled: content keeps its environmental label (always UNTRUSTED, confidentiality from
// classification) joined with the labels of the arguments that selected it.

export type ToolImpl = (values: Record<string, unknown>, labels: Record<string, Label>, sandbox: RunSandbox) => Labeled<unknown>;

/** Output depends on both the content and the arguments that chose it. */
function withArgs(content: Label, labels: Record<string, Label>): Label {
  return joinLabels([content, ...Object.values(labels)]);
}

/** Receipts generated by the tool itself (not derived from external content). */
function receiptLabel(tool: string): Label {
  return makeLabel("TRUSTED", "PUBLIC", [`tool:${tool}`]);
}

const readFile: ToolImpl = (values, labels, sandbox) => {
  const { normalized, content } = readContainedFile(sandbox.files, values.path);
  return labeled({ path: normalized, content }, withArgs(fileContentLabel(normalized), labels));
};

const WEB_HOST = /^[a-z0-9-]+(\.[a-z0-9-]+)*\.test$/;

const fetchWeb: ToolImpl = (values, labels, sandbox) => {
  // Defence in depth, independent of policy: only https URLs on reserved .test hosts, served from local
  // fixture files. There is no network client in this module.
  let url: URL;
  try {
    url = new URL(String(values.url));
  } catch {
    throw new SandboxError("PATH_REJECTED", "Malformed URL");
  }
  if (url.protocol !== "https:" || url.username || url.password || url.port !== "" || !WEB_HOST.test(url.hostname)) {
    throw new SandboxError("PATH_REJECTED", "Only https URLs on local .test fixture hosts can be fetched");
  }
  const page = url.pathname === "/" ? "/index.html" : url.pathname.endsWith(".html") ? url.pathname : `${url.pathname}.html`;
  const { content } = readContainedFile(sandbox.web, `${url.hostname}${page}`);
  const canonicalUrl = `https://${url.hostname}${url.pathname}`;
  return labeled({ url: canonicalUrl, html: content }, withArgs(webContentLabel(canonicalUrl), labels));
};

const messageSchema = z
  .object({
    id: z.string().regex(/^msg-[0-9]{1,6}$/),
    from: z.email(),
    to: z.email(),
    subject: z.string().max(300),
    receivedAt: z.string().max(40),
    body: z.string().max(20_000),
  })
  .strict();

const readInbox: ToolImpl = (values, labels, sandbox) => {
  const dir = containedDir(sandbox, sandbox.inbox);
  const limit = typeof values.limit === "number" ? values.limit : 10;
  const names = readdirSync(dir)
    .filter((n) => n.endsWith(".json"))
    .sort()
    .slice(0, limit);
  // Each message keeps its own provenance; the list as a whole carries the join.
  const messages = names.map((name) => {
    const { content } = readContainedFile(dir, name);
    const msg = messageSchema.parse(JSON.parse(content));
    return labeled(msg, emailContentLabel(msg.id));
  });
  const listLabel = joinLabels([receiptLabel("read_inbox"), ...messages.map((m) => m.label), ...Object.values(labels)]);
  return labeled({ messages }, listLabel);
};

const sendEmail: ToolImpl = (values, labels, sandbox) => {
  const subject = String(values.subject);
  if (/[\r\n]/.test(subject)) throw new SandboxError("PATH_REJECTED", "Email subject must be a single line");
  const dir = containedDir(sandbox, sandbox.outbox);
  const seq = readdirSync(dir).filter((n) => n.endsWith(".json")).length + 1;
  const messageId = `out-${String(seq).padStart(4, "0")}`;
  // The outbox record keeps per-argument provenance as evidence of where each part of the email came from.
  const record = {
    id: messageId,
    runId: sandbox.runId,
    to: values.to,
    subject,
    body: values.body,
    provenance: labels,
    note: "SANDBOX OUTBOX - this email was not sent",
  };
  writeFileSync(path.join(dir, `${messageId}.json`), JSON.stringify(record, null, 2), { flag: "wx" });
  return labeled({ messageId, to: values.to }, receiptLabel("send_email"));
};

const deleteFile: ToolImpl = (values, _labels, sandbox) => {
  const { real, normalized } = resolveContainedFile(sandbox.files, values.path);
  unlinkSync(real);
  return labeled({ deleted: normalized }, receiptLabel("delete_file"));
};

export const TOOL_IMPLS: Readonly<Record<string, ToolImpl>> = Object.freeze({
  read_file: readFile,
  fetch_web: fetchWeb,
  read_inbox: readInbox,
  send_email: sendEmail,
  delete_file: deleteFile,
});
