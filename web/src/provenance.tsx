import { IconAlert, IconLink, IconLock, IconShieldCheck } from "./icons";
import type { Argument, Label } from "./types";
import { cx } from "./ui";

// Provenance visualisation. Shows labels and sources only — argument values are never available to the browser.

const LEVELS = ["PUBLIC", "INTERNAL", "CONFIDENTIAL", "SECRET"] as const;
const LEVEL_COLOR: Record<string, string> = {
  PUBLIC: "bg-slate-400",
  INTERNAL: "bg-sky-400",
  CONFIDENTIAL: "bg-amber-400",
  SECRET: "bg-rose-500",
};

export function IntegrityBadge({ integrity }: { integrity: Label["integrity"] }) {
  const trusted = integrity === "TRUSTED";
  const unknown = integrity === "UNKNOWN";
  return (
    <span
      className={cx(
        "inline-flex items-center gap-1 rounded-md px-2 py-0.5 text-xs font-semibold ring-1 ring-inset",
        trusted ? "bg-emerald-400/10 text-emerald-300 ring-emerald-400/25" : unknown ? "bg-white/5 text-slate-300 ring-white/10" : "bg-rose-500/10 text-rose-300 ring-rose-400/30",
      )}
      title={trusted ? "Comes from the user or their profile" : "Derived from content the agent read or generated"}
    >
      {trusted ? <IconShieldCheck size={13} /> : <IconAlert size={13} />}
      {integrity}
    </span>
  );
}

/** Four-step confidentiality meter: PUBLIC < INTERNAL < CONFIDENTIAL < SECRET. */
export function ConfidentialityMeter({ level }: { level: Label["confidentiality"] }) {
  const idx = LEVELS.indexOf(level as (typeof LEVELS)[number]);
  return (
    <span className="inline-flex items-center gap-1.5" title={`Confidentiality: ${level}`}>
      <span className="flex gap-0.5" aria-hidden>
        {LEVELS.map((l, i) => (
          <span key={l} className={cx("h-2.5 w-1.5 rounded-sm", i <= idx ? LEVEL_COLOR[level] : "bg-white/10")} />
        ))}
      </span>
      <span className={cx("text-xs font-semibold", level === "SECRET" ? "text-rose-300" : level === "CONFIDENTIAL" ? "text-amber-300" : "text-slate-300")}>{level}</span>
    </span>
  );
}

const sourceKind = (s: string) =>
  s.startsWith("web:") ? "web" : s.startsWith("inbox:") ? "inbox" : s.startsWith("file:") ? "file" : s.startsWith("user:") ? "user" : s === "agent:generated" ? "agent" : s.startsWith("tool:") ? "tool" : "other";
const SOURCE_STYLE: Record<string, string> = {
  web: "text-rose-200 bg-rose-500/10 ring-rose-400/20",
  inbox: "text-rose-200 bg-rose-500/10 ring-rose-400/20",
  file: "text-amber-200 bg-amber-400/10 ring-amber-400/20",
  user: "text-emerald-200 bg-emerald-400/10 ring-emerald-400/20",
  agent: "text-sky-200 bg-sky-400/10 ring-sky-400/20",
  tool: "text-slate-200 bg-white/5 ring-white/10",
  other: "text-slate-300 bg-white/5 ring-white/10",
};

export function SourceChips({ sources }: { sources: string[] }) {
  if (sources.length === 0) return <span className="text-xs text-slate-500">no recorded sources</span>;
  return (
    <span className="inline-flex flex-wrap gap-1">
      {sources.map((s) => (
        <span key={s} className={cx("inline-flex items-center gap-1 rounded px-1.5 py-0.5 font-mono text-[11px] ring-1 ring-inset", SOURCE_STYLE[sourceKind(s)])}>
          <IconLink size={11} />
          {s}
        </span>
      ))}
    </span>
  );
}

export function LabelInline({ label }: { label: Label | null }) {
  if (!label) return <span className="text-xs text-slate-500">no label</span>;
  return (
    <span className="inline-flex flex-wrap items-center gap-2">
      <IntegrityBadge integrity={label.integrity} />
      <ConfidentialityMeter level={label.confidentiality} />
    </span>
  );
}

/** Per-argument provenance table: name, integrity, confidentiality, sources. */
export function ArgumentProvenance({ args, compact }: { args: Argument[]; compact?: boolean }) {
  if (args.length === 0) return <p className="text-sm text-slate-500">This call has no arguments.</p>;
  return (
    <ul className="divide-y divide-line">
      {args.map((a) => (
        <li key={a.name} className={cx("grid items-center gap-x-3 gap-y-1.5", compact ? "grid-cols-[6rem_1fr] py-2" : "grid-cols-1 py-2.5 sm:grid-cols-[7rem_auto_1fr]")}>
          <code className="flex items-center gap-1.5 font-mono text-sm text-slate-200">
            <IconLock size={12} className="text-slate-500" />
            {a.name}
          </code>
          <LabelInline label={a} />
          {!compact && <SourceChips sources={a.sources} />}
        </li>
      ))}
    </ul>
  );
}

/** Legend explaining how to read provenance. */
export function ProvenanceLegend() {
  return (
    <div className="grid gap-3 text-sm text-slate-400 sm:grid-cols-3">
      <p>
        <IntegrityBadge integrity="TRUSTED" /> came from the user's task or profile. <IntegrityBadge integrity="UNTRUSTED" /> was read from
        a web page, inbox or file, or generated by the agent after reading such content.
      </p>
      <p>
        <ConfidentialityMeter level="SECRET" /> confidentiality only ever rises as data is combined; the run context remembers everything the
        agent has read.
      </p>
      <p>
        <SourceChips sources={["web:…", "user:task"]} /> sources show exactly where each argument's data came from.
      </p>
    </div>
  );
}
